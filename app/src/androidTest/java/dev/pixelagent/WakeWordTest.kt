import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.Locale
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit

/** Local synthesis and native decoding only. Never sends a conversation or opens the mic. */
@RunWith(AndroidJUnit4::class)
class WakeWordTest {
    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()
    private val context get() = instrumentation.targetContext

    @Test fun bundledTokenizerMatchesSentencePieceReferenceAndPreferenceSurvivesRecreation() {
        val tokenizer = WakeWordTokenizer.fromModel(context.assets.open("keyword/bpe.model"))
        // Expected pieces generated by the official SentencePiece encoder with the pinned model.
        assertEquals("▁JE N K IN S", tokenizer.encode("Jenkins"))
        assertEquals("▁HE LL O ▁WORLD", tokenizer.encode("hello world"))
        assertEquals("▁HE Y ▁JE N K IN S", tokenizer.encode("Hey Jenkins"))
        assertEquals("▁ L IGHT ▁UP", tokenizer.encode("light up"))
        assertEquals("▁COMP U TER", tokenizer.encode("computer"))
        val isolated = object : ContextWrapper(context) {
            override fun getSharedPreferences(name: String, mode: Int) =
                super.getSharedPreferences("wake-word-test-only", mode)
        }
        val prefs = isolated.getSharedPreferences("hands_free", Context.MODE_PRIVATE)
        prefs.edit().clear().commit()
        try {
            assertEquals("Jenkins", WakeWordSettings(isolated).phrase)
            WakeWordSettings(isolated).save("  Hey   Jenkins  ")
            assertEquals("Hey Jenkins", WakeWordSettings(isolated).phrase)
            assertThrows(IllegalArgumentException::class.java) { WakeWordSettings(isolated).save("Jenkins @other") }
            assertEquals("Hey Jenkins", WakeWordSettings(isolated).phrase)
        } finally { prefs.edit().clear().commit() }
    }

    @Test fun nativeEngineDetectsJenkinsFromOfflineSynthesizedSpeech() {
        val initialized = CountDownLatch(1)
        val completed = CountDownLatch(1)
        var status = TextToSpeech.ERROR
        var synthStatus = TextToSpeech.ERROR
        var speech: TextToSpeech? = null
        val wav = File(context.cacheDir, "wake-word-test.wav")
        try {
            instrumentation.runOnMainSync {
                speech = TextToSpeech(context) { status = it; initialized.countDown() }
            }
            assertTrue("TTS initialization timed out", initialized.await(30, TimeUnit.SECONDS))
            assertEquals(TextToSpeech.SUCCESS, status)
            val tts = speech!!
            tts.voice = tts.voices.first { it.locale == Locale.US && !it.isNetworkConnectionRequired }
            tts.setOnUtteranceProgressListener(object : UtteranceProgressListener() {
                override fun onStart(id: String?) { }
                override fun onDone(id: String?) { synthStatus = TextToSpeech.SUCCESS; completed.countDown() }
                @Deprecated("Legacy callback")
                override fun onError(id: String?) { completed.countDown() }
            })
            assertEquals(TextToSpeech.SUCCESS, tts.synthesizeToFile("Jenkins", Bundle(), wav, "jenkins-test"))
            assertTrue("TTS synthesis timed out", completed.await(30, TimeUnit.SECONDS))
            assertEquals(TextToSpeech.SUCCESS, synthStatus)
            val audio = ByteBuffer.wrap(wav.readBytes()).order(ByteOrder.LITTLE_ENDIAN)
            assertEquals("RIFF", String(audio.array(), 0, 4, Charsets.US_ASCII))
            var rate = 0
            var samples = floatArrayOf()
            audio.position(12)
            while (audio.remaining() >= 8) {
                val tag = ByteArray(4).also { audio.get(it) }.toString(Charsets.US_ASCII)
                val size = audio.int
                val end = audio.position() + size
                if (tag == "fmt ") {
                    assertEquals(1, audio.short.toInt()) // PCM
                    assertEquals(1, audio.short.toInt()) // mono
                    rate = audio.int
                    audio.position(audio.position() + 6)
                    assertEquals(16, audio.short.toInt())
                } else if (tag == "data") samples = FloatArray(size / 2) { audio.short / 32768f }
                audio.position(end + size % 2)
            }
            assertTrue(rate > 0 && samples.isNotEmpty())
            val engine = KeywordSpotter(context.assets, KeywordSpotterConfig(
                modelConfig = OnlineModelConfig(transducer = OnlineTransducerModelConfig(
                    encoder = "keyword/encoder-epoch-12-avg-2-chunk-16-left-64.int8.onnx",
                    decoder = "keyword/decoder-epoch-12-avg-2-chunk-16-left-64.onnx",
                    joiner = "keyword/joiner-epoch-12-avg-2-chunk-16-left-64.int8.onnx"),
                    tokens = "keyword/tokens.txt", modelType = "zipformer2", numThreads = 1),
                keywordsFile = "keyword/keywords.txt"))
            try {
                val stream = engine.createStream(WakeWordSettings(context).tokens("Jenkins"))
                try {
                    stream.acceptWaveform(samples + FloatArray(rate), rate)
                    var detected = false
                    while (engine.isReady(stream)) {
                        engine.decode(stream)
                        if (engine.getResult(stream).keyword.isNotBlank()) detected = true
                    }
                    assertTrue("Expected Jenkins in locally synthesized speech", detected)
                } finally { stream.release() }
            } finally { engine.release() }
        } finally { speech?.shutdown(); wav.delete() }
    }
}
